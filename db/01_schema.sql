-- Schema documentation. Read by src/schema.py and injected into the LLM prompt.
-- Every comment states units, allowed values, and grain, because those are exactly
-- the facts a column type cannot express and a wrong assumption about them produces
-- SQL that runs and returns the wrong number.
-- =============================================================================

