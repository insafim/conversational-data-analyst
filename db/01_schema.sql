  'Container terminals. One row per terminal. A port may contain several terminals.';
COMMENT ON COLUMN terminals.terminal_name IS 'Terminal name, unique across all ports.';
COMMENT ON COLUMN terminals.port_name     IS 'Port the terminal belongs to, e.g. Rotterdam, Singapore.';
COMMENT ON COLUMN terminals.country       IS 'Country the port is located in.';
COMMENT ON COLUMN terminals.berth_count   IS 'Number of berths available at this terminal (capacity proxy).';
COMMENT ON COLUMN terminals.opened_year   IS 'Calendar year the terminal opened.';

COMMENT ON TABLE vessels IS
  'Ships that call at the terminals. One row per vessel.';
COMMENT ON COLUMN vessels.vessel_name  IS 'Ship name. Not guaranteed unique; use vessel_id to identify a vessel.';
COMMENT ON COLUMN vessels.imo_number   IS 'IMO registration number, exactly 7 digits, unique per vessel.';
COMMENT ON COLUMN vessels.vessel_type  IS 'One of: Container Ship, Bulk Carrier, Ro-Ro, Tanker.';
COMMENT ON COLUMN vessels.capacity_teu IS 'Maximum capacity in TEU (twenty-foot equivalent units). Capacity, NOT actual cargo carried.';
COMMENT ON COLUMN vessels.operator     IS 'Shipping line operating the vessel. Use this column for questions about carriers, lines, or operators.';
COMMENT ON COLUMN vessels.flag_country IS 'Country of registration (flag state).';
COMMENT ON COLUMN vessels.year_built   IS 'Calendar year the vessel was built.';

COMMENT ON TABLE cranes IS
  'Quay cranes. One row per crane. Each crane belongs to exactly one terminal and can only service vessels berthed at that terminal.';
COMMENT ON COLUMN cranes.terminal_id       IS 'Terminal that owns this crane. A crane never works at another terminal.';
COMMENT ON COLUMN cranes.crane_code        IS 'Short operational identifier, unique across terminals, e.g. RTM-QC-03.';
COMMENT ON COLUMN cranes.model             IS 'Manufacturer model designation.';
COMMENT ON COLUMN cranes.commissioned_date IS 'Date the crane entered service. Use for questions about crane age.';
COMMENT ON COLUMN cranes.max_lift_tonnes   IS 'Maximum safe working load in tonnes.';
COMMENT ON COLUMN cranes.status            IS 'One of: active, maintenance, retired.';

COMMENT ON TABLE port_calls IS
  'Vessel visits. One row per visit of a vessel to a terminal. This is the grain for berth wait, dwell time and visit-count questions.';
COMMENT ON COLUMN port_calls.vessel_id    IS 'Vessel making the call. Join to vessels for operator, type or capacity.';
COMMENT ON COLUMN port_calls.terminal_id  IS 'Terminal being visited. Join to terminals for port or country.';
COMMENT ON COLUMN port_calls.arrival_ts   IS 'When the vessel arrived in the port area and began waiting for a berth.';
COMMENT ON COLUMN port_calls.berth_ts     IS 'When the vessel was allocated a berth and cargo work could begin. NULL for cancelled calls.';
COMMENT ON COLUMN port_calls.departure_ts IS 'When the vessel left the berth. NULL for cancelled calls.';
COMMENT ON COLUMN port_calls.status       IS 'One of: completed, cancelled. Cancelled calls never berthed and have NULL berth_ts, departure_ts and berth_wait_hours.';
COMMENT ON COLUMN port_calls.berth_wait_hours IS
  'HOURS waited at anchor between arrival_ts and berth_ts, computed automatically. This is the standard congestion metric: use AVG(berth_wait_hours) for "average waiting time" questions. NULL for cancelled calls, so AVG ignores them.';

COMMENT ON TABLE cargo_moves IS
  'Container handling activity. One row per batch of container moves performed by one crane during one port call. Finer grain than port_calls: a single port call has many cargo_moves rows.';
COMMENT ON COLUMN cargo_moves.port_call_id     IS 'Port call this work belongs to. Join to port_calls for vessel, terminal and timing.';
COMMENT ON COLUMN cargo_moves.crane_id         IS 'Crane that performed the moves. Always belongs to the same terminal as the port call.';
COMMENT ON COLUMN cargo_moves.move_type        IS 'One of: load (containers onto the vessel), discharge (containers off the vessel).';
COMMENT ON COLUMN cargo_moves.container_count  IS 'Number of containers moved in this batch. SUM this column for throughput or volume questions.';
COMMENT ON COLUMN cargo_moves.move_ts          IS 'When this batch of moves was performed.';
COMMENT ON COLUMN cargo_moves.duration_minutes IS 'MINUTES taken to complete the batch. Crane productivity = container_count / (duration_minutes / 60.0) moves per hour.';
