-- =============================================================================
-- Conversational Data Analyst — schema for port & terminal operations
-- See docs/ADR/ADR-001-domain-and-data-model.md
--
-- IMPORTANT: the COMMENT ON statements at the bottom of this file are functional,
-- not decorative. src/schema.py introspects them and injects them into the
-- SQL-generation prompt as schema context (ADR-003). They are how the model learns
-- units, enum values, and the meaning of near-identical timestamp columns. Treat
-- them as production code: if you change a column, change its comment.
--
-- Timestamps are `timestamp without time zone`, deliberately. Terminal operations
-- are reasoned about in local port time, and — critically — timestamptz arithmetic
-- is only STABLE, not IMMUTABLE, which would make the generated column below
-- illegal. See the note on berth_wait_hours.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- Dimension: terminals
-- ---------------------------------------------------------------------------
CREATE TABLE terminals (
    terminal_id   integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_name text         NOT NULL,
    port_name     text         NOT NULL,
    country       text         NOT NULL,
    berth_count   smallint     NOT NULL,
    opened_year   smallint     NOT NULL,
    CONSTRAINT terminals_name_unique     UNIQUE (terminal_name),
    CONSTRAINT terminals_berth_count_chk CHECK (berth_count BETWEEN 1 AND 30),
    CONSTRAINT terminals_opened_year_chk CHECK (opened_year BETWEEN 1900 AND 2100)
);

-- ---------------------------------------------------------------------------
-- Dimension: vessels
-- ---------------------------------------------------------------------------
CREATE TABLE vessels (
    vessel_id    integer  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vessel_name  text     NOT NULL,
    imo_number   char(7)  NOT NULL,
    vessel_type  text     NOT NULL,
    capacity_teu integer  NOT NULL,
    operator     text     NOT NULL,
    flag_country text     NOT NULL,
    year_built   smallint NOT NULL,
    CONSTRAINT vessels_imo_unique      UNIQUE (imo_number),
    CONSTRAINT vessels_type_chk        CHECK (vessel_type IN
                                        ('Container Ship', 'Bulk Carrier', 'Ro-Ro', 'Tanker')),
    CONSTRAINT vessels_capacity_chk    CHECK (capacity_teu > 0),
    CONSTRAINT vessels_year_built_chk  CHECK (year_built BETWEEN 1950 AND 2100)
);

-- ---------------------------------------------------------------------------
-- Dimension: cranes (equipment, owned by exactly one terminal)
-- ---------------------------------------------------------------------------
CREATE TABLE cranes (
    crane_id          integer  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id       integer  NOT NULL,
    crane_code        text     NOT NULL,
    model             text     NOT NULL,
    commissioned_date date     NOT NULL,
    max_lift_tonnes   smallint NOT NULL,
    status            text     NOT NULL,
    CONSTRAINT cranes_terminal_fk   FOREIGN KEY (terminal_id)
                                    REFERENCES terminals (terminal_id),
    CONSTRAINT cranes_code_unique   UNIQUE (crane_code),
    CONSTRAINT cranes_status_chk    CHECK (status IN ('active', 'maintenance', 'retired')),
    CONSTRAINT cranes_max_lift_chk  CHECK (max_lift_tonnes > 0)
);

-- ---------------------------------------------------------------------------
-- Fact: port_calls — one row per vessel visit to a terminal
-- ---------------------------------------------------------------------------
CREATE TABLE port_calls (
    port_call_id integer   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vessel_id    integer   NOT NULL,
    terminal_id  integer   NOT NULL,
    arrival_ts   timestamp NOT NULL,
    berth_ts     timestamp,
    departure_ts timestamp,
    status       text      NOT NULL,

    -- Hours spent waiting at anchor between arriving in the port area and being
    -- allocated a berth. This is THE congestion metric for the domain.
    --
    -- STORED is specified explicitly because PostgreSQL 18 changed the default kind of
    -- generated column to VIRTUAL. Omitting it here would silently produce a virtual
    -- column, which cannot be indexed.
    -- (https://www.postgresql.org/docs/18/ddl-generated-columns.html)
    --
    -- The expression is legal only because these are `timestamp` not `timestamptz`
    -- columns: timestamp subtraction is IMMUTABLE, whereas the timestamptz equivalent
    -- is STABLE and generation expressions may only use immutable functions.
    berth_wait_hours numeric(10, 2)
        GENERATED ALWAYS AS (EXTRACT(EPOCH FROM (berth_ts - arrival_ts)) / 3600.0) STORED,

    CONSTRAINT port_calls_vessel_fk   FOREIGN KEY (vessel_id)   REFERENCES vessels (vessel_id),
    CONSTRAINT port_calls_terminal_fk FOREIGN KEY (terminal_id) REFERENCES terminals (terminal_id),
    CONSTRAINT port_calls_status_chk  CHECK (status IN ('completed', 'cancelled')),
    -- NULL-tolerant by design: a cancelled call never berths, so berth_ts and
    -- departure_ts are NULL and these comparisons evaluate to NULL, which passes.
    CONSTRAINT port_calls_berth_after_arrival_chk   CHECK (berth_ts     >= arrival_ts),
    CONSTRAINT port_calls_depart_after_berth_chk    CHECK (departure_ts >= berth_ts),
    -- A completed call must have both timestamps; a cancelled one must have neither.
    CONSTRAINT port_calls_status_consistency_chk CHECK (
        (status = 'completed' AND berth_ts IS NOT NULL AND departure_ts IS NOT NULL)
        OR
        (status = 'cancelled' AND berth_ts IS NULL AND departure_ts IS NULL)
    )
);

-- ---------------------------------------------------------------------------
-- Fact: cargo_moves — one row per crane move batch within a port call
-- ---------------------------------------------------------------------------
CREATE TABLE cargo_moves (
    move_id          integer   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    port_call_id     integer   NOT NULL,
    crane_id         integer   NOT NULL,
    move_type        text      NOT NULL,
    container_count  integer   NOT NULL,
    move_ts          timestamp NOT NULL,
    duration_minutes smallint  NOT NULL,
    CONSTRAINT cargo_moves_port_call_fk FOREIGN KEY (port_call_id)
                                        REFERENCES port_calls (port_call_id),
    CONSTRAINT cargo_moves_crane_fk     FOREIGN KEY (crane_id) REFERENCES cranes (crane_id),
    CONSTRAINT cargo_moves_type_chk     CHECK (move_type IN ('load', 'discharge')),
    CONSTRAINT cargo_moves_count_chk    CHECK (container_count > 0),
    CONSTRAINT cargo_moves_duration_chk CHECK (duration_minutes > 0)
);

-- ---------------------------------------------------------------------------
-- Indexes: foreign keys (PostgreSQL does not create these automatically) and the
-- timestamp columns used for time-series grouping.
-- ---------------------------------------------------------------------------
CREATE INDEX cranes_terminal_idx          ON cranes      (terminal_id);
CREATE INDEX port_calls_vessel_idx        ON port_calls  (vessel_id);
CREATE INDEX port_calls_terminal_idx      ON port_calls  (terminal_id);
CREATE INDEX port_calls_arrival_ts_idx    ON port_calls  (arrival_ts);
CREATE INDEX port_calls_terminal_time_idx ON port_calls  (terminal_id, arrival_ts);
CREATE INDEX cargo_moves_port_call_idx    ON cargo_moves (port_call_id);
CREATE INDEX cargo_moves_crane_idx        ON cargo_moves (crane_id);
CREATE INDEX cargo_moves_move_ts_idx      ON cargo_moves (move_ts);

